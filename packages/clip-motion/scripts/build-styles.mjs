#!/usr/bin/env node
/**
 * styles/<id>/{style.json,STYLE.md,example.jsx} → styles/index.gen.ts, so the web app and the MCP server get each
 * motion style's guide and example scene as plain strings.
 *
 *   node scripts/build-styles.mjs           write
 *   node scripts/build-styles.mjs --check   exit 1 when index.gen.ts is out of date
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'styles');
const OUT = join(ROOT, 'index.gen.ts');

const styles = readdirSync(ROOT)
	.filter((name) => statSync(join(ROOT, name)).isDirectory())
	.sort()
	.map((id) => {
		const meta = JSON.parse(readFileSync(join(ROOT, id, 'style.json'), 'utf8'));
		if (meta.id !== id) throw new Error(`styles/${id}/style.json has id "${meta.id}"`);
		return { ...meta, guide: readFileSync(join(ROOT, id, 'STYLE.md'), 'utf8').trim(), code: readFileSync(join(ROOT, id, 'example.jsx'), 'utf8') };
	});

const text = `// Generated by scripts/build-styles.mjs from styles/<id>/{style.json,STYLE.md,example.jsx}. Do not edit.\n\nexport const STYLE_DATA = ${JSON.stringify(styles, null, '\t')};\n`;

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(OUT, 'utf8');
	} catch {}
	if (current !== text) {
		console.error('styles/index.gen.ts is out of date: run node packages/clip-motion/scripts/build-styles.mjs');
		process.exit(1);
	}
} else {
	writeFileSync(OUT, text);
	console.log(`wrote ${OUT} (${styles.length} styles)`);
}
