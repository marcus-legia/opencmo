// Writes src/kit/lotties.ts from packages/clip-media/lottie (a test keeps them equal).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { lottieNames } from '../src/lottie-files.ts';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'kit', 'lotties.ts');
const names = lottieNames();
writeFileSync(
	out,
	`// Generated by scripts/build-lotties.ts from packages/clip-media/lottie: do not edit.\n` +
		`// The OpenCMO pack is CC0; emoji/* are Noto Emoji Animation (CC BY 4.0), see that folder's LICENSE.md.\n\n` +
		`export const LOTTIE_NAMES: readonly string[] = ${JSON.stringify(names, null, '\t').replace(/"/g, "'")};\n`,
);
console.log(`${names.length} animations → ${out}`);
