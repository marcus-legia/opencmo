#!/usr/bin/env node
/**
 * templates/<id>/{template.json,scene.jsx,SPEC.md} → templates/index.gen.ts, so the web app and the MCP server
 * get the scene code as plain strings (no file reads at run time, nothing for the bundler to trace).
 *
 *   node scripts/build-templates.mjs           write
 *   node scripts/build-templates.mjs --check   exit 1 when index.gen.ts is out of date
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'templates');
const OUT = join(ROOT, 'index.gen.ts');

const templates = readdirSync(ROOT)
	.filter((name) => statSync(join(ROOT, name)).isDirectory())
	.sort()
	.map((id) => {
		const meta = JSON.parse(readFileSync(join(ROOT, id, 'template.json'), 'utf8'));
		if (meta.id !== id) throw new Error(`templates/${id}/template.json has id "${meta.id}"`);
		return { ...meta, direction: readFileSync(join(ROOT, id, 'SPEC.md'), 'utf8').trim(), code: readFileSync(join(ROOT, id, 'scene.jsx'), 'utf8') };
	});

const text = `// Generated by scripts/build-templates.mjs from templates/<id>/{template.json,scene.jsx,SPEC.md}. Do not edit.\n\nexport const TEMPLATE_DATA = ${JSON.stringify(templates, null, '\t')};\n`;

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(OUT, 'utf8');
	} catch {}
	if (current !== text) {
		console.error('templates/index.gen.ts is out of date: run node packages/clip-motion/scripts/build-templates.mjs');
		process.exit(1);
	}
} else {
	writeFileSync(OUT, text);
	console.log(`wrote ${OUT} (${templates.length} templates)`);
}
