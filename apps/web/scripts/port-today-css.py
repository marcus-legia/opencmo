#!/usr/bin/env python3
"""
Ports the CSS of the "OpenCMO Today" canvas artboards (claude.ai/artifact/77MyWuSem4GCssg7Bx11wi) into
apps/web/styles/today.css, verbatim except for scope:

- every rule of artboard <Name>.dc.html is prefixed with `.pg-<name>`, so artboards that reuse a class name with a
  different look (`.chip`, `.row`, `.drawer`...) do not collide; the app puts `k pg-<name>` on the screen's root;
- `@media (prefers-color-scheme:dark){...}` becomes `html[data-theme="dark"] ...`, so the app's own System / Light /
  Dark choice works (THEME_BOOT resolves System from the same media query);
- `body` rules are dropped (the page root `.k` carries the background) and keyframes get a per-page name.

Run from apps/web: python3 scripts/port-today-css.py ../../docs/design/today-canvas > styles/today.css
"""
import re
import sys
from pathlib import Path

PAGES = ["Main", "Calendar", "AgentSales", "Context", "Analytics", "Editor", "AgentWriter", "Logs", "Setup", "Projects", "Settings", "Prompter"]


def split_rules(css):
    """Top-level blocks: (prelude, body) where body is the text between the matching braces."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < n:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        out.append((prelude, css[j + 1 : k - 1]))
        i = k
    return out


def scope_selector(sel, page, dark):
    sel = sel.strip()
    root = f".k.pg-{page}"
    pre = 'html[data-theme="dark"] ' if dark else ""
    if sel == "body" or sel.startswith("body "):
        return None
    if sel == ".k" or sel.startswith(".k ") or sel.startswith(".k.") or sel.startswith(".k:") or sel.startswith(".k["):
        return pre + root + sel[2:]
    return f"{pre}.pg-{page} {sel}"


def scope_rules(css, page, dark=False):
    lines = []
    for prelude, body in split_rules(css):
        if prelude.startswith("@keyframes"):
            name = prelude.split()[1]
            lines.append(f"@keyframes {name}-{page}{{{body}}}")
        elif prelude.startswith("@media"):
            if "prefers-color-scheme" in prelude:
                inner = scope_rules(body, page, dark=True)
                if inner:
                    lines.append(inner)
            else:
                inner = scope_rules(body, page, dark)
                if inner:
                    lines.append(f"{prelude}{{{inner}}}")
        else:
            sels = [s for s in (scope_selector(x, page, dark) for x in prelude.split(",")) if s]
            if sels:
                lines.append(f"{','.join(sels)}{{{body}}}")
    return "\n".join(lines)


def page_css(path, page):
    html = path.read_text()
    css = re.search(r"<style>(.*?)</style>", html, re.S).group(1)
    names = set(re.findall(r"@keyframes\s+([\w-]+)", css))
    scoped = scope_rules(css, page)
    # Point animations at the per-page keyframes.
    for name in sorted(names, key=len, reverse=True):
        scoped = re.sub(rf"(animation:[^;{{}}]*?)\b{name}\b(?!-{page})", rf"\1{name}-{page}", scoped)
    return scoped


def main():
    folder = Path(sys.argv[1])
    print("/* Generated by scripts/port-today-css.py from the canvas artboards: do not edit by hand. */")
    print('@font-face{font-family:Geist;src:url("/fonts/geist.woff2") format("woff2");font-weight:100 900;font-display:swap}')
    print('@font-face{font-family:"Geist Mono";src:url("/fonts/geist-mono.woff2") format("woff2");font-weight:100 900;font-display:swap}')
    for page in PAGES:
        print(f"\n/* ---- {page}.dc.html ---- */")
        print(page_css(folder / f"{page}.dc.html", page.lower()))


main()
